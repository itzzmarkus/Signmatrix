#!/usr/bin/env python3
import json
import os
from sync_fonts import decode_png_white_mask

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(SCRIPT_DIR)
FONTS_DIR = os.path.join(PROJECT_DIR, "fonts")

OUTPUT_FILE = os.path.join(PROJECT_DIR, "src", "data", "transitLogos.js")

FONT_CONFIGS = [
    {
        "font": "smartgraphics",
        "fontLabel": "Luminator Smart (20px)",
        "json": os.path.join(FONTS_DIR, "smart", "graphics.json"),
        "png": os.path.join(FONTS_DIR, "smart", "graphics.png"),
        "id_prefix": "smart"
    },
    {
        "font": "logo",
        "fontLabel": "Hanover (14px)",
        "json": os.path.join(FONTS_DIR, "hanover", "LOGO.json"),
        "png": os.path.join(FONTS_DIR, "hanover", "LOGO.png"),
        "id_prefix": "logo14"
    },
    {
        "font": "logo16",
        "fontLabel": "Hanover (16px)",
        "json": os.path.join(FONTS_DIR, "hanover", "LOGO16.json"),
        "png": os.path.join(FONTS_DIR, "hanover", "LOGO16.png"),
        "id_prefix": "logo16"
    }
]


def generate():
    all_logos = []

    for cfg in FONT_CONFIGS:
        json_path = cfg["json"]
        png_path = cfg["png"]

        if not os.path.exists(json_path) or not os.path.exists(png_path):
            raise FileNotFoundError(f"Missing font file: {json_path} or {png_path}")

        with open(json_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        _, _, is_white = decode_png_white_mask(png_path)
        height = data["height"]

        for glyph in data.get("glyphs", []):
            char = glyph["char"]
            if char == " " or char.strip() == "":
                continue

            x = glyph["x"]
            y = glyph.get("y", 0)
            w = glyph["w"]

            rows = []
            for dy in range(height):
                row_str = ""
                for dx in range(w):
                    row_str += "1" if is_white[y + dy][x + dx] else "0"
                rows.append(row_str)

            char_code = ord(char)
            logo_id = f"{cfg['id_prefix']}-{char_code}"

            all_logos.append({
                "id": logo_id,
                "char": char,
                "font": cfg["font"],
                "fontLabel": cfg["fontLabel"],
                "height": height,
                "width": w,
                "rows": rows
            })

    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    with open(OUTPUT_FILE, "w", encoding="utf-8") as out:
        out.write("// Auto-generated by scripts/sync_icons.py from fonts/ JSONs and PNGs\n")
        out.write("// Total icons: " + str(len(all_logos)) + "\n")
        out.write("export const TRANSIT_LOGOS = ")
        json.dump(all_logos, out, indent=2)
        out.write(";\n\nexport default TRANSIT_LOGOS;\n")

    print(f"Successfully generated {len(all_logos)} icons into {OUTPUT_FILE}")


if __name__ == "__main__":
    generate()
